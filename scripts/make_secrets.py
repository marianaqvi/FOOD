#!/usr/bin/env python3
"""Create firmware/secrets.py (git-ignored) for the board. Run it yourself in a terminal:

    python3 scripts/make_secrets.py

It asks for the Wi-Fi name and password here (the password is not echoed and is never printed or
logged), finds this Mac's LAN IP and the dev device token, and writes firmware/secrets.py with
owner-only permissions. Nothing is uploaded; scripts/deploy_board.py does that on request.
"""
import getpass
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "secrets.py")
TOKEN = os.path.join(ROOT, "web", ".data", "dev-device-token")


def lan_ip():
    for iface in ("en0", "en1"):
        try:
            ip = subprocess.run(["ipconfig", "getifaddr", iface], capture_output=True, text=True, timeout=5).stdout.strip()
            if ip:
                return ip
        except Exception:
            pass
    return ""


def main():
    if os.path.exists(OUT) and "--force" not in sys.argv:
        raise SystemExit("firmware/secrets.py already exists; edit it, or rerun with --force to replace it")
    if not os.path.exists(TOKEN):
        raise SystemExit("no device token yet: start the server once with MOCK_MODE=1 npm run dev (it creates web/.data/dev-device-token)")
    ssid = input("Wi-Fi name (SSID): ").strip()
    pw = getpass.getpass("Wi-Fi password (hidden): ")
    ip = input("Mac LAN IP [%s]: " % lan_ip()).strip() or lan_ip()
    if not ssid or not pw or not ip:
        raise SystemExit("SSID, password and IP are all required")
    with open(TOKEN) as fh:
        token = fh.read().strip()
    text = "# GENERATED by scripts/make_secrets.py. Git-ignored. Never commit.\nWIFI_SSID = %r\nWIFI_PASSWORD = %r\nSERVER_HOST = %r\nSERVER_PORT = 3000\nDEVICE_TOKEN = %r\n" % (ssid, pw, ip, token)
    fd = os.open(OUT, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    print("wrote firmware/secrets.py (owner-only). Server address the board will use: http://%s:3000" % ip)


if __name__ == "__main__":
    main()
