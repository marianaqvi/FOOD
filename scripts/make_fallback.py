#!/usr/bin/env python3
"""Write firmware/fallback.py: the first idle frame, byte for byte, taken from the packed idle.bin.

The firmware shows this static frame only if the animation files or manifest on the board are
missing or corrupt. It is NOT a redrawn sprite: it is record 0 of the canonical idle reaction.

    python3 scripts/pack_assets.py && python3 scripts/make_fallback.py
    python3 scripts/make_fallback.py --check
"""
import binascii
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "firmware", "assets", "idle.bin")
DST = os.path.join(ROOT, "firmware", "fallback.py")
RECORD = 770


def render():
    with open(SRC, "rb") as fh:
        rec = fh.read(RECORD)
    if len(rec) != RECORD:
        raise SystemExit("idle.bin is shorter than one record")
    hexs = binascii.hexlify(rec).decode("ascii")
    lines = [hexs[i:i + 96] for i in range(0, len(hexs), 96)]
    body = "\n".join('    "%s"' % ln for ln in lines)
    return (
        "# firmware/fallback.py  (GENERATED by scripts/make_fallback.py, do not edit)\n"
        "# Record 0 of the canonical idle reaction, byte for byte: u16le duration + three 256-byte masks.\n"
        "# Shown only when the animation files on the board are missing or corrupt.\n"
        "import binascii\n\n"
        "_HEX = (\n%s\n)\n\n"
        "RECORD = binascii.unhexlify(_HEX)\n" % body
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = os.path.exists(DST) and open(DST).read() == text
        print("fallback.py is up to date" if ok else "fallback.py is STALE")
        sys.exit(0 if ok else 1)
    with open(DST, "w") as fh:
        fh.write(text)
    print("wrote", DST)
